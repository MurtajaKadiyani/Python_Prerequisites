# 1. Importing the built-in 'math' module
import math

print("Square root of 25:", math.sqrt(25))  # Output: 5.0
print("Value of pi:", math.pi)  # Output: 3.141592653589793

# 2. Importing the built-in 'random' module
import random
secret_number = random.randint(1,10) # Generates a random integer between 1 and 10
print("Random Number", secret_number)
